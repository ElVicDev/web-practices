/* Un arreglo es una colección indexada.
    Las posiciones de índice comienzan desde 0.
    El elemento en la primera posición está en el índice 0,
    el segundo elemento está en la posición 1, y así sucesivamente.
    El índice de la última posición siempre será uno menos que la longitud del arreglo. */

let myArray = ["Jack", "Jill", 4, 5, true, "John"];
console.log(myArray[0]);
console.log(myArray[5]);
